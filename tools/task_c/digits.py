def pen_paths(text):
    if not text.isdigit() or len(text) > 2:
        raise ValueError("Only one or two decimal digits are supported")
    width = 65 if len(text) == 1 else 45
    left = 65 if len(text) == 1 else 35
    result = []
    for index, digit in enumerate(text):
        for stroke in DIGITS[digit]:
            result.append([(round(255 - (65 + vertical * 115)),
                            round(left + index * 75 + horizontal * width))
                           for horizontal, vertical in stroke])
    return result
